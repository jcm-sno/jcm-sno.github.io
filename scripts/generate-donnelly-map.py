#!/usr/bin/env python3
"""Render a static Cambridge context map from the city's public-domain GeoJSON.

Run: python scripts/generate-donnelly-map.py [cached-data-directory]
No map service, API key, or network request is needed by site visitors.
"""

import html
import json
import math
from pathlib import Path
import re
import sys
import tempfile
import urllib.request


ROOT = Path(__file__).resolve().parents[1]
CACHE = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(tempfile.gettempdir()) / "jcm-sno-cambridge-map"
BASE = "https://raw.githubusercontent.com/cambridgegis/cambridgegis_data/main/"
LAYERS = {
    "parks": "Recreation/Open_Space/RECREATION_OpenSpace.geojson",
    "water": "Hydro/Water_Bodies/HYDRO_WaterBodies.geojson",
    "streets": "Trans/Street_Centerlines/TRANS_Centerlines.geojson",
    "stations": "Trans/Subway_Stations/TRANS_SubwayStations.geojson",
}
WIDTH, HEIGHT = 900, 720
NORTH, SOUTH = 42.3735, 42.355
WEST = -71.1005
# Preserve local distances in the east-west and north-south directions.
EAST = WEST + (NORTH - SOUTH) * WIDTH / HEIGHT / math.cos(math.radians((NORTH + SOUTH) / 2))


def project(point):
    lon, lat = point[:2]
    return ((lon - WEST) / (EAST - WEST) * WIDTH, (NORTH - lat) / (NORTH - SOUTH) * HEIGHT)


def points(coords):
    if isinstance(coords[0], (int, float)):
        yield coords
    else:
        for item in coords:
            yield from points(item)


def visible(feature):
    coords = list(points(feature["geometry"]["coordinates"]))
    return not (
        max(p[0] for p in coords) < WEST or min(p[0] for p in coords) > EAST
        or max(p[1] for p in coords) < SOUTH or min(p[1] for p in coords) > NORTH
    )


def simplify(line, tolerance=0.55):
    """Ramer–Douglas–Peucker in output pixels, keeping real geographic shapes."""
    if len(line) < 3:
        return line
    ax, ay = line[0]
    bx, by = line[-1]
    dx, dy = bx - ax, by - ay
    length = dx * dx + dy * dy
    distances = []
    for x, y in line[1:-1]:
        t = max(0, min(1, ((x - ax) * dx + (y - ay) * dy) / length)) if length else 0
        distances.append(math.hypot(x - ax - t * dx, y - ay - t * dy))
    maximum = max(distances)
    if maximum <= tolerance:
        return [line[0], line[-1]]
    index = distances.index(maximum) + 1
    return simplify(line[:index + 1], tolerance)[:-1] + simplify(line[index:], tolerance)


def path(feature):
    geometry = feature["geometry"]
    kind, coords = geometry["type"], geometry["coordinates"]
    if kind == "LineString":
        rings = [coords]
    elif kind in ("Polygon", "MultiLineString"):
        rings = coords
    elif kind == "MultiPolygon":
        rings = [ring for polygon in coords for ring in polygon]
    else:
        return ""
    result = []
    for ring in rings:
        line = simplify([project(p) for p in ring])
        result.append("M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in line))
        if "Polygon" in kind:
            result.append("Z")
    return " ".join(result)


def load_layer(name, source):
    CACHE.mkdir(parents=True, exist_ok=True)
    target = CACHE / f"{name}.json"
    if not target.exists():
        with urllib.request.urlopen(BASE + source, timeout=30) as response:
            target.write_bytes(response.read())
    return json.loads(target.read_text())["features"]


layers = {name: load_layer(name, source) for name, source in LAYERS.items()}
field = next(f for f in layers["parks"] if f["properties"].get("NAME") == "Donnelly Field")
square = next(f for f in layers["parks"] if f["properties"].get("NAME") == "Kendall Square")
station = next(f for f in layers["stations"] if f["properties"].get("STATION") == "KENDALL/MIT")
kx, ky = project(station["geometry"]["coordinates"])

svg = ['''<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="900" height="720" viewBox="0 0 900 720" role="img" aria-labelledby="title desc">
<title id="title">Donnelly Field, Kendall Square, and the Charles River</title>
<desc id="desc">North is up. Donnelly Field is highlighted in green northwest of Kendall Square, marked in red at Kendall/MIT. The Charles River, in blue, curves along Cambridge to the south and east. Streets and shorelines follow City of Cambridge geographic data.</desc>
<metadata>Map data: City of Cambridge GIS, PDDL 1.0. Open Space, Water Bodies, Street Centerlines, and Subway Stations. https://github.com/cambridgegis/cambridgegis_data . Static map generated by scripts/generate-donnelly-map.py.</metadata>
<defs>
  <clipPath id="map-extent"><rect width="900" height="720"/></clipPath>
  <style>
    .street {font: 500 16px Arial,sans-serif; fill:#6c756f}
    .place {font: 700 31px Georgia,serif}
    .small {font: 600 16px Arial,sans-serif; letter-spacing:2px; fill:#53645d}
  </style>
</defs>
<rect width="900" height="720" fill="#fffdf8"/>
<g clip-path="url(#map-extent)">
''']

for feature in layers["parks"]:
    if visible(feature):
        svg.append(f'<path d="{path(feature)}" fill="#e4eadb" stroke="#cbd7c1" stroke-width="1" fill-rule="evenodd"/>')
for feature in layers["water"]:
    if visible(feature):
        svg.append(f'<path d="{path(feature)}" fill="#9ccddd" stroke="#6ca9bf" stroke-width="1.5" fill-rule="evenodd"/>')

streets = [feature for feature in layers["streets"] if visible(feature)]
major_names = {"Cambridge St", "Hampshire St", "Broadway", "Main St", "Memorial Dr", "Third St", "Land Blvd", "Longfellow Brg", "Binney St"}
for outer in (True, False):
    for major in (False, True):
        width = (7 if major else 4) if outer else (4.5 if major else 2.4)
        color = "#c9c9bf" if outer else "#fffdf8"
        svg.append(f'<g fill="none" stroke="{color}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">')
        for feature in streets:
            if (feature["properties"].get("Street") in major_names) == major:
                svg.append(f'<path d="{path(feature)}"/>')
        svg.append('</g>')

svg.append(f'<path d="{path(field)}" fill="#6faf82" stroke="#276a3e" stroke-width="3" fill-rule="evenodd"/>')
svg.append(f'<path d="{path(square)}" fill="#c85c50" stroke="#a34239" stroke-width="2" fill-rule="evenodd"/>')
svg.append('</g>')

# A few orientation labels; these are placed along actual street segments.
for name, target in [
    ("Cambridge St", (480, 115)),
    ("Hampshire St", (140, 280)),
    ("Broadway", (300, 345)),
    ("Main St", (245, 455)),
    ("Memorial Dr", (280, 580)),
    ("Third St", (565, 270)),
]:
    candidates = []
    for feature in streets:
        if feature["properties"].get("Street") != name:
            continue
        line = [project(p) for p in feature["geometry"]["coordinates"]]
        a, b = line[0], line[-1]
        x, y = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
        if 55 < x < 845 and 55 < y < 645:
            candidates.append((math.hypot(x-target[0], y-target[1]), x, y, a, b))
    if candidates:
        _, x, y, a, b = min(candidates)
        angle = math.degrees(math.atan2(b[1]-a[1], b[0]-a[0]))
        if angle > 90:
            angle -= 180
        if angle < -90:
            angle += 180
        svg.append(f'<text class="street" x="{x:.1f}" y="{y-5:.1f}" text-anchor="middle" transform="rotate({angle:.1f} {x:.1f} {y:.1f})">{html.escape(name)}</text>')

svg += [
    '<path d="M245 77 L245 98" fill="none" stroke="#276a3e" stroke-width="2.5"/>',
    '<text class="place" x="245" y="66" fill="#276a3e" text-anchor="middle">Donnelly Field</text>',
    f'<circle cx="{kx:.1f}" cy="{ky:.1f}" r="10" fill="#bb4e43" stroke="#fffdf8" stroke-width="3"/>',
    f'<path d="M{kx+12:.1f} {ky-4:.1f} L{kx+29:.1f} {ky-24:.1f} H{kx+43:.1f}" fill="none" stroke="#bb4e43" stroke-width="2.5"/>',
    f'<text class="place" x="{kx+47:.1f}" y="{ky-18:.1f}" fill="#a34239">Kendall Square</text>',
    '<text x="647" y="580" text-anchor="middle" transform="rotate(-27 647 580)" font-family="Georgia,serif" font-size="34" font-style="italic" fill="#275b78">Charles River</text>',
    '<text class="small" x="185" y="548">MIT</text>',
    '<g transform="translate(838 30)"><path d="M0 30 L12 0 L24 30 L12 22 Z" fill="#294c40"/><text class="small" x="12" y="52" text-anchor="middle">N</text></g>',
]

# Scale derives from the map projection, rather than an illustrative distance.
scale_width = 250 / (111_320 * (NORTH - SOUTH) / HEIGHT)
svg += [
    '<g transform="translate(32 654)"><rect x="-10" y="-10" width="147" height="57" rx="3" fill="#fffdf8" fill-opacity=".94"/>',
    f'<path d="M0 0 V8 H{scale_width:.1f} V0" fill="none" stroke="#53645d" stroke-width="2"/>',
    '<text class="small" x="0" y="34">250 m</text></g>',
    '</svg>',
]
output = ROOT / "public/donnelly-field-map.svg"
# Separate halo and foreground text works in browsers and basic SVG renderers.
markup = re.sub(
    r'(<text class="(?:street|place|small)"[^>]*)(>[^<]*</text>)',
    lambda m: m[1] + ' stroke="#fffdf8" stroke-width="6" stroke-linejoin="round"' + m[2]
    + m[1] + ' stroke="none"' + m[2],
    "\n".join(svg),
)
output.write_text(markup + "\n")
print(f"Wrote {output} ({output.stat().st_size:,} bytes)")
